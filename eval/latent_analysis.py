# Categorical: the first three slots of the reference palette, which are the
# ones that clear the all-pairs CVD and normal-vision floors (scatter puts every
# pair on screen at once, so the adjacent-pair ordering guarantee does not
# apply). Worst all-pairs CVD dE 9.2, normal-vision 24.0. Aqua sits at 2.74:1 on
