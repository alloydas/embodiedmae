def panels_for(tgt):
    """Show the split panel only when more than one split is on screen."""
    multi = tgt['split'].nunique() > 1
    return _PANELS_BASE + [(_PANEL_SPLIT if multi else _PANEL_WAV), _PANEL_CLUSTER]


def style(ax):
    """Recessive axes: the marks carry the chart, the frame does not."""
    for s in ('top', 'right'):
        ax.spines[s].set_visible(False)
    for s in ('left', 'bottom'):
        ax.spines[s].set_color('#dcdbd6')
        ax.spines[s].set_linewidth(0.8)
    ax.tick_params(colors=INK_3, labelsize=7, length=3, width=0.8)
    ax.set_facecolor('#fcfcfb')


# ── analysis ─────────────────────────────────────────────────────────────────

def structure(X):
    """PCA spectrum and effective rank."""
    from sklearn.decomposition import PCA
    Xc = X - X.mean(0, keepdims=True)
    p = PCA().fit(Xc)
    ev = p.explained_variance_ratio_
    # participation ratio: (sum l)^2 / sum l^2 -- how many directions the
    # variance actually occupies, without a cutoff to argue about.
    lam = p.explained_variance_
    pr = float(lam.sum() ** 2 / (lam ** 2).sum())
    return {
        'dim': int(X.shape[1]),
        'pc1_var': float(ev[0]),
        'pc1_3_var': float(ev[:3].sum()),
        'n_pcs_90': int(np.searchsorted(np.cumsum(ev), 0.90) + 1),
        'n_pcs_95': int(np.searchsorted(np.cumsum(ev), 0.95) + 1),
        'participation_ratio': pr,
    }, p


def factor_alignment(X, tgt, cols, n_pc=5):
    """|pearson r| between each leading PC and each true generative factor."""
    from sklearn.decomposition import PCA
    Z = PCA(n_components=n_pc).fit_transform(X - X.mean(0, keepdims=True))
    rows = []
    for c in cols:
        y = tgt[c].to_numpy(dtype=np.float64)
        rs = [abs(float(np.corrcoef(Z[:, k], y)[0, 1])) for k in range(n_pc)]
        rows.append({'factor': c, **{f'|r| PC{k+1}': rs[k] for k in range(n_pc)},
                     'best_pc': int(np.argmax(rs)) + 1, 'best_|r|': max(rs)})
    return pd.DataFrame(rows)


def cluster_tendency(X, tgt, ks=(2, 3, 4, 6, 8, 10, 12), seed=0):
    """Is this a set of clusters, or one continuum?

    Silhouette near 0 means the partition is arbitrary. ARI against shape
    deciles asks whether whatever partition k-means does find corresponds to
    anything real.
    """
    from sklearn.cluster import KMeans
    from sklearn.metrics import silhouette_score, adjusted_rand_score
    size_bin = pd.qcut(tgt['n_leaves'].rank(method='first'), 10, labels=False)
    rows = []
    for k in ks:
        km = KMeans(n_clusters=k, n_init=10, random_state=seed).fit(X)
        rows.append({
            'k': k,
            'silhouette': float(silhouette_score(X, km.labels_, sample_size=min(2000, len(X)), random_state=seed)),
            'ari_vs_size_decile': float(adjusted_rand_score(size_bin, km.labels_)),
            'inertia': float(km.inertia_),
        })
    return pd.DataFrame(rows)


def neighbourhood(X, tgt, cols, emb2d=None, seed=0, n=1500):
    """Do latent neighbours share shape?

    Two different questions, deliberately kept apart:
      * spearman(latent distance, shape distance) -- does the LATENT order
        plants the way the generator does? This is the E9 result.
      * trustworthiness -- does the 2-D picture preserve the latent's own
        neighbourhoods? This is a caveat on the figure, not a result about the
        model, so it needs the real embedding rather than a stand-in
        projection. Skipped when no embedding is supplied.
    """
    from scipy.spatial.distance import pdist
    from scipy.stats import spearmanr
    from sklearn.preprocessing import StandardScaler
    rng = np.random.default_rng(seed)
    idx = rng.choice(len(X), size=min(n, len(X)), replace=False)
    Xs = X[idx]
    S = StandardScaler().fit_transform(tgt.iloc[idx][cols].to_numpy(float))
    rho, _ = spearmanr(pdist(Xs), pdist(S))
    out = {'n_sampled': int(len(idx)),
           'spearman_latent_vs_shape_dist': float(rho)}
    if emb2d is not None:
        from sklearn.manifold import trustworthiness
        out['tsne_trustworthiness_k10'] = float(
            trustworthiness(Xs, emb2d[idx], n_neighbors=10))
    return out


def embed(X, seed=0, perplexity=30):
    """PCA-50 then t-SNE; UMAP too when it is installed."""
    from sklearn.decomposition import PCA
    from sklearn.manifold import TSNE
    X50 = PCA(n_components=min(50, X.shape[1]), random_state=seed).fit_transform(X)
    out = {'tsne': TSNE(n_components=2, perplexity=perplexity, init='pca',
                        random_state=seed).fit_transform(X50)}
    try:
        import umap
        out['umap'] = umap.UMAP(n_components=2, random_state=seed).fit_transform(X50)
    except ImportError:
        print('  (umap-learn not installed in this env — t-SNE only. '
              'Not installing it: these conda envs are shared with running jobs.)')
    return out


# ── figure ───────────────────────────────────────────────────────────────────

def figure(emb, tgt, clusters, run, split, method, path):
    fig, axes = plt.subplots(2, 3, figsize=(13.5, 8.6), facecolor='#fcfcfb')
    fig.suptitle(f'E9 · latent structure — {run} · {split} split · {method.upper()}',
                 fontsize=13, color=INK, x=0.5, y=0.985, ha='center')

    for ax, (col, title, kind, cmap) in zip(axes.ravel(), panels_for(tgt)):
        style(ax)
        ax.set_title(title, fontsize=9.5, color=INK, pad=7, loc='left')
        ax.set_xticks([]); ax.set_yticks([])
        if kind == 'cat':
            for name, colour in CAT.items():
                m = (tgt['split'] == name).to_numpy()
                if m.any():
                    ax.scatter(emb[m, 0], emb[m, 1], s=3, c=colour, alpha=.75,
                               linewidths=0, label=f'{name} (n={int(m.sum())})')
            # legend is the documented relief for aqua's sub-3:1 contrast, and
            # keeps identity off colour alone
            lg = ax.legend(loc='upper right', fontsize=7.5, frameon=False,
                           markerscale=3, labelcolor=INK_2)
            for t in lg.get_texts():
                t.set_color(INK_2)
        elif kind == 'clu':
            # a partition of a continuum: greys, deliberately not the
            # categorical hues, so it never reads as a real grouping
            k = int(clusters.max()) + 1
            for c in range(k):
                m = clusters == c
                ax.scatter(emb[m, 0], emb[m, 1], s=3, alpha=.75, linewidths=0,
                           c=[plt.cm.Greys(0.30 + 0.55 * c / max(k - 1, 1))])
            ax.text(.02, .02, f'k={k}', transform=ax.transAxes,
                    fontsize=7.5, color=INK_3)
        else:
            v = tgt[col].to_numpy(dtype=np.float64)
            lo, hi = np.percentile(v, [2, 98])      # clip so outliers don't
            sc = ax.scatter(emb[:, 0], emb[:, 1], s=5, c=np.clip(v, lo, hi),
                            cmap=cmap, alpha=.9, linewidths=0)
            cb = fig.colorbar(sc, ax=ax, fraction=.045, pad=.02)
            cb.ax.tick_params(labelsize=7, colors=INK_3, length=2)
            cb.outline.set_visible(False)

    fig.text(0.5, 0.012,
             'No genotype label exists in Sorghum_15K — one generator, seed = plant id. '
             'A continuous latent is the expected result, not a failed clustering.',
             ha='center', fontsize=8, color=INK_3)
    fig.tight_layout(rect=[0, 0.03, 1, 0.96])
    fig.savefig(path, dpi=170, facecolor='#fcfcfb')
    plt.close(fig)
    print(f'  🖼  {path}')


# ── main ─────────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--runs', nargs='+', required=True)
    ap.add_argument('--split', default='val', choices=('train', 'val', 'test'))
    ap.add_argument('--ckpt', default='best_model.pth')
    ap.add_argument('--data-root', default=LP.DATA_ROOT)
    ap.add_argument('--feature', default='cls', choices=('cls', 'mean', 'cls+mean'))
    ap.add_argument('--batch-size', type=int, default=32)
    ap.add_argument('--num-workers', type=int, default=16)
    ap.add_argument('--device', default='cuda')
    ap.add_argument('--seed', type=int, default=0)
    ap.add_argument('--repeats', type=int, default=1)
    ap.add_argument('--cache-dir', default=str(LP.REPO / 'outputs' / '_probe_cache'))
    ap.add_argument('--refresh', action='store_true')
    ap.add_argument('--out-dir', default=str(LP.REPO / 'reports'))
    ap.add_argument('--fig-dir', default=str(LP.REPO / 'figures'))
    args = ap.parse_args()

    if args.device.startswith('cuda') and not torch.cuda.is_available():
        print('⚠️  no CUDA — fine if every cache is warm, fatal if any is cold')
        args.device = 'cpu'

    out_dir, fig_dir = Path(args.out_dir), Path(args.fig_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    fig_dir.mkdir(parents=True, exist_ok=True)

    tgt_all = LP.load_targets(args.data_root)
    SHAPE = ['n_leaves', 'stem_length', 'leaf_len_mean', 'leaf_len_max']

    print(__doc__.split('Usage')[0])

    summary = []
    for run in args.runs:
        run_dir = LP.REPO / 'outputs' / run if not Path(run).exists() else Path(run)
        slug = Path(run_dir).name
        print(f'\n=== {slug} · {args.split} ===')

        cache = Path(args.cache_dir) / (
            f'{slug}__{Path(args.ckpt).stem}__{args.split}__{args.feature}'
            f'__seed{args.seed}__rep{args.repeats}.npz')
        if cache.exists() and not args.refresh:
            z = np.load(cache)
            plants, X = z['plants'], z['feats']
            print(f'  ⚡ cache hit {cache.name} {X.shape}')
        else:
            model, cfg, epoch = LP.build_model(run_dir, args.ckpt, args.device)
            plants, X = LP.cached_features(model, cfg, args, slug, args.split)
            del model
            if args.device.startswith('cuda'):
                torch.cuda.empty_cache()

        tgt = tgt_all.reindex(plants)
        X = X.astype(np.float64)

        st, _ = structure(X)
        print(f'  structure: dim {st["dim"]} · PC1 {st["pc1_var"]:.1%} · '
              f'PC1-3 {st["pc1_3_var"]:.1%} · 90% at {st["n_pcs_90"]} PCs · '
              f'participation ratio {st["participation_ratio"]:.1f}')

        fa = factor_alignment(X, tgt, SHAPE)
        print('  factor alignment (|r| with leading PCs):')
        print('   ', fa[['factor', 'best_pc', 'best_|r|']].to_string(index=False).replace('\n', '\n    '))

        ct = cluster_tendency(X, tgt)
        best = ct.loc[ct['silhouette'].idxmax()]
        print(f'  cluster tendency: best silhouette {best["silhouette"]:.3f} at k={int(best["k"])} '
              f'(ARI vs size decile {best["ari_vs_size_decile"]:.3f})')
        print('    -> silhouette < 0.25 means no real clusters, which is the '
              'expected result for a continuous generator.')

        embs = embed(X, seed=args.seed)

        nb = neighbourhood(X, tgt, SHAPE, emb2d=embs.get('tsne'), seed=args.seed)
        print(f'  neighbourhood: spearman(latent dist, shape dist) = '
              f'{nb["spearman_latent_vs_shape_dist"]:+.3f} on {nb["n_sampled"]} plants'
              + (f' · t-SNE trustworthiness {nb["tsne_trustworthiness_k10"]:.3f}'
                 if 'tsne_trustworthiness_k10' in nb else ''))

        from sklearn.cluster import KMeans
        clusters = KMeans(n_clusters=6, n_init=10, random_state=args.seed).fit_predict(X)
        for method, E in embs.items():
            figure(E, tgt, clusters, slug, args.split, method,
                   fig_dir / f'e9_latent_{slug}_{args.split}_{method}.png')

        fa.to_csv(out_dir / f'e9_factor_alignment_{slug}_{args.split}.csv', index=False)
        ct.to_csv(out_dir / f'e9_cluster_tendency_{slug}_{args.split}.csv', index=False)
        summary.append({'run': slug, 'split': args.split, 'n_plants': len(plants),
                        **st, **nb,
                        'best_silhouette': float(best['silhouette']),
                        'best_silhouette_k': int(best['k']),
                        'ari_at_best_k': float(best['ari_vs_size_decile']),
                        # column is literally named 'best_|r|', which itertuples
                        # would rename to a positional field -- index the frame
                        **{f'align_{f}': float(v) for f, v in
                           zip(fa['factor'], fa['best_|r|'])}})

    df = pd.DataFrame(summary)
    p = out_dir / f'e9_latent_summary_{args.split}.csv'
    df.to_csv(p, index=False)
    print(f'\n📄 {p}')
    cols = ['run', 'participation_ratio', 'pc1_var', 'best_silhouette',
            'spearman_latent_vs_shape_dist', 'align_n_leaves', 'align_leaf_len_mean']
    print('\n' + df[[c for c in cols if c in df]].to_string(index=False))


if __name__ == '__main__':
    main()
