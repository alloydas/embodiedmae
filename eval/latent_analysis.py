CAT = {'train': '#2a78d6', 'val': '#eb6834', 'test': '#1baf7a'}
# Sequential: ONE hue per scale, light -> dark. Never a rainbow WITHIN a scale --
# a multi-hue ramp on a continuous factor reads as categorical, which is exactly
# the thing this script exists to measure. But six panels are six separate
# sequential contexts, and the palette's rule for that case is that each takes
# the next categorical slot's hue as its own one-hue ramp. So the figure is
# colourful across panels and strictly single-hue within one.
def _ramp(anchor, name):
    """Light -> dark ramp at the anchor's hue. Lightness is the encoding."""
    import colorsys
    from matplotlib.colors import to_rgb
    h, _l, sat = colorsys.rgb_to_hls(*to_rgb(anchor))
    stops = []
    for t in np.linspace(0.0, 1.0, 9):
        L = 0.93 - 0.74 * t                     # monotone light -> dark
        S = min(1.0, sat * (0.50 + 0.62 * t))   # saturate as it darkens
        stops.append(colorsys.hls_to_rgb(h, L, S))
    return LinearSegmentedColormap.from_list(name, stops)

