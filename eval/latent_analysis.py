#!/usr/bin/env python3
"""E9 — latent analysis. Clustering and t-SNE/UMAP over the frozen encoder latent.

The plan specifies E9 as "clustering, t-SNE/UMAP by genotype and shape", eval
only. Half of that is directly buildable and half is not, so read this first:

THERE IS NO GENOTYPE VARIABLE IN Sorghum_15K.
Every plant is generated by `SorghumGenerator/Random.sg` with `Seed: <plant id>`
-- one generator, one continuous parameter distribution, 15,000 independent
draws. The seed is an identifier, not a cultivar: plant 0 and plant 1 are not
two genotypes, they are two samples from one family. So "cluster by genotype"
has nothing to condition on, and a k-means partition of this latent would be
cutting a continuum into arbitrary pieces and then reporting the pieces.

That makes the *honest* E9 question a different and stronger one:

    Does the latent recover the generative factors, and is it continuous?

A latent that encodes a continuous generator well should show LOW cluster
separation (no genuine clusters exist) and HIGH factor alignment / neighbourhood
fidelity. Reporting a low silhouette here is a positive result, not a failure --
which is exactly why it has to be said before the number is read. This script
therefore reports:

  1. Intrinsic structure  -- PCA spectrum, effective rank (participation ratio).
  2. Factor alignment     -- |corr| of leading PCs with the true shape factors.
  3. Cluster tendency     -- k-means silhouette over k, plus ARI against shape
                             deciles. The expected answer is "no clusters".
  4. Neighbourhood        -- trustworthiness, and Spearman(latent dist, shape
                             dist): are a plant's latent neighbours its shape
                             neighbours?
  5. Embeddings           -- t-SNE (and UMAP when installed) coloured by each
                             factor.

SHAPE IS TWO AXES, NOT FOUR. features.csv has rank ~2: the generator sets
stem_length = 0.05 x n_leaves, so height and leaf count are one variable, and
the biomass proxy is that variable again. PC1 of the tabular factors is size,
PC2 is leaf size, and everything else is sampling noise. Colouring six panels by
six columns would show the same gradient six times; the panels below are chosen
to span the two real axes instead.

Usage
-----
    python eval/latent_analysis.py --runs e2_pcrgbdt
    python eval/latent_analysis.py --runs e2_pc e2_pcrgb e2_pcrgbd e2_pcrgbdt \\
                                   --split val --out-dir reports

Features come from the same cache `eval/linear_probe.py` writes, so once the
probe has run this costs no GPU at all. If the cache is cold it extracts
(and needs a GPU).
"""

